export function formatDate(dateInput: string | Date | undefined, lang: Language = 'th', era: CalendarEra = 'buddhist'): string {
  if (!dateInput) return '-';
  const d = new Date(dateInput);
  if (isNaN(d.getTime())) return '-';

  const day = d.getDate();
  const year = d.getFullYear();
  const displayYear = era === 'buddhist' ? year + 543 : year;
  
  const thaiMonths = [
    'ม.ค.', 'ก.พ.', 'มี.ค.', 'เม.ย.', 'พ.ค.', 'มิ.ย.',
    'ก.ค.', 'ส.ค.', 'ก.ย.', 'ต.ค.', 'พ.ย.', 'ธ.ค.'
  ];
  const englishMonths = [
    'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'
  ];

  if (lang === 'th') {
    return `${day} ${thaiMonths[d.getMonth()]} ${displayYear}`;
  } else {
    return `${day} ${englishMonths[d.getMonth()]} ${displayYear}`;
  }
}
